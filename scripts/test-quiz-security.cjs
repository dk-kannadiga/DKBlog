const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {publicQuiz}=require('../js/quiz-security.js');
const source=fs.readFileSync('integrations/quiz-grading/Code.gs','utf8');
const ctx=vm.createContext({Date,JSON,Number,Array,Error,encodeURIComponent});
vm.runInContext(source,ctx);
const quiz={id:123,title:'Test',type:'certificate',state:'live',questions:[{q:'One?',opts:['A','B'],ans:1,exp:'PRIVATE EXPLANATION'},{q:'Two?',opts:['C','D','E'],ans:0}],stats:{secret:true}};
const published=publicQuiz(quiz,'version');
assert.equal(JSON.stringify(published).includes('PRIVATE'),false);
assert.equal('ans' in published.questions[0],false);
assert.equal('stats' in published,false);
assert.equal('exp' in published.questions[0],false);
assert.throws(()=>publicQuiz({...quiz,questions:[{q:'x',opts:['a','b'],ans:2}]},'v'));
const key={questions:quiz.questions,version:'version',locked:true};
const request={quizId:'123',participantName:'Name',contact:'test@example.invalid',answers:[1,0],score:999,userId:'forged'};
const grade=(r=request,q=published,k=key)=>ctx.validateQuizAnswers_(r,q,k);
assert.equal(grade(),2); // forged score and identity are never used
assert.equal(grade({...request,answers:[0,-1]}),0);
for(const answers of [[1],[1,0,0],[1,9],[1,0.5],[1,'0'],[1,-2],null])assert.throws(()=>grade({...request,answers}),/INVALID_ANSWERS/);
for(const state of ['closed','upcoming','archived'])assert.throws(()=>grade(request,{...published,state}),/QUIZ_CLOSED/);
assert.throws(()=>grade(request,null),/QUIZ_CLOSED/);
assert.throws(()=>grade(request,{...published,id:456}),/QUIZ_CLOSED/);
assert.throws(()=>grade(request,{...published,version:'changed'}),/QUIZ_CHANGED/);
assert.throws(()=>grade(request,published,{...key,locked:false}),/QUIZ_CHANGED/);
assert.throws(()=>grade(request,{...published,questions:[{q:'Altered',opts:['A','B']},published.questions[1]]}),/QUIZ_CHANGED/);
assert.throws(()=>grade({...request,participantName:''}),/INVALID_NAME/);
assert.throws(()=>grade({...request,contact:''},{...published,type:'prize'}),/INVALID_CONTACT/);
for(const type of ['prize','certificate'])for(const contact of ['', '9876543210', 'invalid@'])assert.throws(()=>grade({...request,contact},{...published,type}),/INVALID_CONTACT/);
assert.equal(grade({...request,contact:'test@example.invalid'},{...published,type:'prize'}),2);
// Authentication: forged JWT claims never bypass the Firebase lookup.
const claims={aud:'dkblog-6c5e5',iss:'https://securetoken.google.com/dkblog-6c5e5',sub:'visitor',exp:Date.now()/1000+300,iat:Date.now()/1000};
ctx.Utilities={base64DecodeWebSafe:s=>Buffer.from(s,'base64url'),newBlob:b=>({getDataAsString:()=>b.toString()})};
let lookupStatus=400,lookupUser='visitor';
ctx.UrlFetchApp={fetch:(url,options)=>{assert.match(url,/identitytoolkit/);assert.equal(options.headers,undefined);return {getResponseCode:()=>lookupStatus,getContentText:()=>JSON.stringify({users:[{localId:lookupUser}]})}}};
const token=c=>`header.${Buffer.from(JSON.stringify(c)).toString('base64url')}.signature`;
assert.throws(()=>ctx.verifyQuizUser_(token(claims)),/UNAUTHENTICATED/);
lookupStatus=200;
assert.equal(ctx.verifyQuizUser_(token(claims)),'visitor');
lookupUser='other';assert.throws(()=>ctx.verifyQuizUser_(token(claims)),/UNAUTHENTICATED/);
assert.throws(()=>ctx.verifyQuizUser_(token({...claims,aud:'other-project'})),/UNAUTHENTICATED/);
assert.throws(()=>ctx.verifyQuizUser_(token({...claims,exp:0})),/UNAUTHENTICATED/);
// Transactions: live state, keys and existing result are read together; creates are immutable.
const writes=[];let existing=null,transactionOpen=false,liveQuiz=published;
ctx.quizRpc_=(suffix,body)=>{if(suffix===':beginTransaction'){transactionOpen=true;return {transaction:'tx'}}if(suffix===':rollback'){transactionOpen=false;return {}}throw Error(suffix)};
ctx.quizRead_=(path,tx)=>{assert.equal(tx,'tx');assert.equal(transactionOpen,true);return path==='siteSettings/activeQuiz'?{quiz:liveQuiz}:path.startsWith('quizKeys/')?key:existing};
ctx.quizCommit_=(items,tx)=>{assert.equal(tx,'tx');items.forEach(w=>assert.equal(w.currentDocument.exists,false));writes.push(...items);transactionOpen=false};
ctx.gradeQuizRequest_(request,'visitor','receipt_visitor');
assert.equal(writes.length,2);
const saved=ctx.quizDecode_({mapValue:{fields:writes[0].update.fields}});
assert.equal(saved.score,2);assert.equal(saved.userId,'visitor');assert.equal(saved.gradingVersion,2);
existing={gradingVersion:2,score:2};writes.length=0;
ctx.gradeQuizRequest_(request,'visitor','another_visitor');assert.equal(writes.length,1);assert.match(writes[0].update.name,/quizReceipts/);
existing={answers:[0,0]};assert.throws(()=>ctx.gradeQuizRequest_(request,'visitor','old_visitor'),/ALREADY_SUBMITTED/);
assert.equal(transactionOpen,false);
existing=null;liveQuiz={...published,type:'prize'};writes.length=0;
ctx.gradeQuizRequest_({...request,contact:'test@example.invalid'},'visitor','prize_visitor');
assert.equal(writes.length,3);
assert.equal('contact' in writes[0].update.fields,false);
assert.match(writes[2].update.name,/prizeQuizEntries/);
assert.equal(ctx.quizDecode_({mapValue:{fields:writes[2].update.fields}}).contact,'test@example.invalid');
liveQuiz={...published,state:'closed'};writes.length=0;
assert.throws(()=>ctx.gradeQuizRequest_(request,'visitor','closed_visitor'),/QUIZ_CLOSED/);
assert.equal(writes.length,0);
assert.equal(transactionOpen,false);
// Both UI result paths use saved server data, and even owner-held keys are not shown live.
const appSource=fs.readFileSync('js/app.js','utf8');
const resultSource=appSource.slice(appSource.indexOf('function showResults('),appSource.indexOf('const CERT_FONT_STACKS='));
const rendered={innerHTML:''};
const renderCtx=vm.createContext({Math,document:{getElementById:()=>rendered},todayStr:()=> '2026-10-01',esc:s=>String(s)});
vm.runInContext(resultSource,renderCtx);
renderCtx.showResults(quiz,[1,0],'Name',1);
assert.match(rendered.innerHTML,/1 \/ 2/);
assert.equal(rendered.innerHTML.includes('PRIVATE EXPLANATION'),false);
renderCtx.showResults({...quiz,state:'archived'},[1,0],'Name',2);
assert.equal(rendered.innerHTML.includes('PRIVATE EXPLANATION'),true);
assert.match(appSource,/saved=await window.saveFirestoreQuizSubmission/);
assert.match(appSource,/showResults\(submittedQuiz,saved.answers,saved.participantName,saved.score/);
const rules=fs.readFileSync('firestore.rules','utf8');
for(const name of ['quizSubmissions','prizeQuizEntries'])assert.match(rules.match(new RegExp('match /'+name+'/[\\s\\S]*?\\n    }'))[0],/allow create, update, delete: if false/);
assert.match(rules,/match \/quizKeys\/\{quizId\} \{\s+allow read, write: if isAdmin\(\)/);
console.log('Quiz security tests passed: private publishing, trusted grading, token verification, closed-state validation, transaction identity and immutable results.');
